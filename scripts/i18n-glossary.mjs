/**
 * Render src/i18n/GLOSSARY.md from glossary.json and report open glossary work by page.
 *
 *   node scripts/i18n-glossary.mjs --write          # regenerate GLOSSARY.md
 *   node scripts/i18n-glossary.mjs --check          # exit 1 when GLOSSARY.md is stale
 *   node scripts/i18n-glossary.mjs --report [page]  # baseline violations grouped by page
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const read = path => JSON.parse(readFileSync(resolve(root, 'src/i18n', path), 'utf8'))
const locales = ['zh-TW', 'zh-CN', 'ja', 'ko', 'es', 'pt', 'fr', 'de', 'ru', 'ar', 'hi', 'id']
const cell = text => String(text).replaceAll('|', '\\|').replaceAll('\n', ' ')

export function renderGlossary(glossary = read('glossary.json')) {
  const lines = [
    '# Translation glossary',
    '',
    '<!-- Generated by scripts/i18n-glossary.mjs from glossary.json. Edit glossary.json, then run `node scripts/i18n-glossary.mjs --write`. -->',
    '',
    'Every locale uses the approved rendering below for each product term, in every message and on every page.',
    'Write each translation from the full English message; the glossary fixes terminology, not sentence structure.',
    '`src/i18n/glossary.test.ts` fails when a translation drops an approved term, uses a listed variant, breaks',
    'the locale register, or exceeds the display-width budget recorded in `usage-notes.json`.',
    '',
    '## Workflow',
    '',
    '1. Look up the message in `usage-notes.json`: its page, element kind (button, table header, label, heading, body…) and `maxWidth`.',
    '2. Translate the whole message with the approved terms below. Buttons and table headers must stay within `maxWidth`',
    '   display columns (East Asian wide characters count as two).',
    '3. Run `npx vitest run src/i18n/glossary.test.ts`. When a fix clears a recorded violation, regenerate the baseline with',
    '   `I18N_BASELINE=update npx vitest run src/i18n/glossary.test.ts`. The baseline may only shrink.',
    '4. `node scripts/i18n-glossary.mjs --report <page>` lists the remaining recorded violations for one page.',
    '',
    'Identifiers (`context=`, `vram`, `owner/repository`), commands, units and publisher names stay in English. Messages whose',
    'English uses a word in an unrelated sense are listed under each term’s exceptions in `glossary.json`.',
    '',
    '## Register',
    '',
    '| Locale | Register |',
    '| --- | --- |',
    ...locales.map(locale => `| ${locale} | ${cell(glossary.style[locale].register)} |`),
    '',
    '## Terms',
    '',
    `| Term | ${locales.join(' | ')} |`,
    `| --- | ${locales.map(() => '---').join(' | ')} |`,
    ...glossary.terms.map(term => `| **${cell(term.en)}** | ${locales.map(locale => cell(term.translations[locale].use)).join(' | ')} |`),
    '',
    '## Meaning and variants to avoid',
    '',
    ...glossary.terms.flatMap(term => {
      const avoided = locales.filter(locale => term.translations[locale].avoid).map(locale => `${locale} \`${term.translations[locale].avoid}\``)
      return [`### ${term.en}`, '', term.sense, '', ...(avoided.length ? [`Avoid: ${avoided.join('; ')}.`, ''] : [])]
    }),
  ]
  return lines.join('\n').replace(/\n+$/, '\n')
}

function report(page) {
  const notes = read('usage-notes.json')
  const baseline = read('glossary-baseline.json')
  const pageOf = new Map()
  for (const [id, entry] of Object.entries(notes.pages)) for (const key of Object.keys(entry.messages)) if (!pageOf.has(key)) pageOf.set(key, id)
  const groups = {}
  for (const id of baseline) {
    const [locale, rule, ...rest] = id.split(' | ')
    const key = rest.join(' | ')
    const target = pageOf.get(key) ?? 'other'
    ;(groups[target] ??= []).push({ locale, rule, key })
  }
  for (const [id, items] of Object.entries(groups).sort((a, b) => b[1].length - a[1].length)) {
    if (page && id !== page) continue
    console.log(`${id} (${notes.pages[id]?.title ?? 'unlocated'}): ${items.length}`)
    if (page) for (const item of items) console.log(`  ${item.locale.padEnd(6)} ${item.rule.padEnd(24)} ${item.key.slice(0, 100)}`)
  }
}

if (process.argv[1] === import.meta.filename) {
  const target = resolve(root, 'src/i18n/GLOSSARY.md')
  if (process.argv.includes('--write')) writeFileSync(target, renderGlossary())
  else if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== renderGlossary()) { console.error('src/i18n/GLOSSARY.md is stale. Run: node scripts/i18n-glossary.mjs --write'); process.exit(1) }
  } else if (process.argv.includes('--report')) report(process.argv[process.argv.indexOf('--report') + 1])
}
